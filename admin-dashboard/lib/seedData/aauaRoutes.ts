import type { RouteRecord } from '../types/route';

// Source: your actual AAUA route data (Design Addendum 1, Section 1).
// lat/lng are null until an admin geocodes/pins each stop (Addendum 1, Section 4) —
// the Route edit screen in this module lets you fill those in per stop later,
// or you can build the dedicated map-pin editor as a follow-up enhancement.
function stops(names: string[]) {
  return names.map((name, index) => ({ order: index + 1, name, lat: null, lng: null }));
}

